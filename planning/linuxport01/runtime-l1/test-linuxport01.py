  for bad in('1\n100','2\n50\n','1\n\n','1\n50\nextra\n','','1 50\n',PMSET_AC):
   with self.subTest(bad=bad),self.assertRaisesRegex(RuntimeError,'UNKNOWN_POWER'):hp.parse_power(bad,'linux')
