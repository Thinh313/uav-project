 # Artifact cap 13 -> 20 MiB; checked key by key in ArtifactCap.
 CAP_AMENDED={'assets/resource-policy.json'}
 def changed(self,name):
  a=(ORIGINAL/name).read_text().splitlines();b=(PORT/name).read_text().splitlines()
  rows=[l for l in difflib.unified_diff(a,b,lineterm='',n=0)if l[:1]in'+-'and not l.startswith(('+++','---'))]
  return[l for l in rows if l[0]=='-'],[l for l in rows if l[0]=='+']
 def test_only_declared_files_and_lines_differ(self):
  same=[p.relative_to(ORIGINAL).as_posix()for p in ORIGINAL.rglob('*')if p.is_file()and(PORT/p.relative_to(ORIGINAL)).read_bytes()!=p.read_bytes()]
  self.assertEqual(sorted(same),sorted([*self.EXPECTED,*self.REGENERATED,*self.CAP_AMENDED]))
  added={p.relative_to(PORT).as_posix()for p in PORT.rglob('*')if p.is_file()}-{p.relative_to(ORIGINAL).as_posix()for p in ORIGINAL.rglob('*')if p.is_file()}
  self.assertEqual(added,{'host_power_platform.py','linux_disk11.py'})
  for name,(removed,inserted)in self.EXPECTED.items():
   with self.subTest(name=name):
    minus,plus=self.changed(name)
    self.assertEqual((len(minus),len(plus)),(removed,inserted))
