class ArtifactCap(unittest.TestCase):
 """13 -> 20 MiB as authorized for H10 (AUTHORIZATION-CAPS03.json). Metadata cap and every other guard unchanged."""
 D=7*2**20
 def policy(self,root):return json.loads((root/'assets/resource-policy.json').read_bytes())
 def test_cap_matches_owner_h10_value(self):
  from aeris_runtime import candidate,metadata_budget
  self.assertEqual(candidate.CAP,20*2**20);self.assertIn('MIB=2**20;CAP=20*MIB;',(H10/'candidate.py').read_text())
  self.assertTrue(candidate.artifact_cap_admitted(candidate.CAP));self.assertFalse(candidate.artifact_cap_admitted(candidate.CAP+1))
  self.assertEqual(metadata_budget.CAP,68*2**20);self.assertEqual((PORT/'metadata_budget.py').read_bytes(),(ORIGINAL/'metadata_budget.py').read_bytes())
 def test_policy_changes_only_artifact_reserve_by_7MiB(self):
  a,b=self.policy(ORIGINAL),self.policy(PORT);h=self.policy(H10);meta=h['campaign']['globalMetadataCapBytes']-a['campaign']['globalMetadataCapBytes']
  changed=[('campaign','newIsolatedAPKAndArchiveReserve'),('campaign','taskHardPeakBytes')]
  for s in('180','760','1960'):changed+=[('cases',s,'budget','categories','newIsolatedAPKAndArchiveReserve'),('cases',s,'budget','requiredFreeBytes'),('cases',s,'budget','taskHardPeakBytes')]
  def get(v,k):
   for x in k:v=v[x]
   return v
  for k in changed:
   with self.subTest(key=k):
    self.assertEqual(get(b,k),get(a,k)+self.D)
    # H10 raised artifact (+7 MiB) and metadata (+32 MiB); ours is H10 minus the metadata part.
    self.assertEqual(get(b,k),get(h,k)-(0 if k[-1]=='newIsolatedAPKAndArchiveReserve' else meta))
  for k in changed:
   x,y=b,a
   for part in k[:-1]:x,y=x[part],y[part]
   x[k[-1]]=y[k[-1]]
  amend=b.pop('betarc01HostCapAmendment');a.pop('betarc01HostCapAmendment')
  self.assertEqual(b,a)
  self.assertEqual(amend['artifactCapBytes'],20*2**20);self.assertEqual(amend['oldArtifactCapBytes'],13*2**20);self.assertEqual(amend['aggregateReserveIncreaseBytes'],self.D)
  self.assertEqual(amend['hostMetadataCapBytes'],amend['oldHostMetadataCapBytes']);self.assertEqual(amend['authorizationPath'],'evidence/betarc01/AUTHORIZATION-CAPS03.json')
  self.assertEqual(amend['authorizationSHA256'],h['betarc01HostCapAmendment']['authorizationSHA256'])
